/**
 * khepri-secure-paste — core.js
 *
 * The PrivateBin-equivalent half. It stores ciphertext and nothing else.
 *
 * Crypto model (matches PrivateBin):
 *   key material = 32 random bytes ++ password bytes
 *   key          = PBKDF2(key material, salt, iterations)
 *   ciphertext   = AES-256-GCM(plaintext, iv, adata=[pasteId])
 *
 * The random bytes travel in the URL fragment (#...). Fragments are never
 * sent to the server, so the server cannot reconstruct the key even with the
 * password — and it never receives the password at all.
 *
 * What the server holds: pasteId, ciphertext, iv, salt, iteration count,
 * adata, an expiry and a burn flag. No key, no password, no plaintext.
 *
 * The pasteId is generated by the browser and validated here. It is not a
 * secret: without the fragment there is no key.
 */

'use strict';

const http = require('node:http');
const fs = require('node:fs');
const path = require('node:path');

const PORT = parseInt(process.env.PORT || '8080', 10);
const TTL_MS = parseInt(process.env.TTL_HOURS || '24', 10) * 3600 * 1000;
const SHORTENER = process.env.SHORTENER_URL || '';
const MAX_BODY = 1024 * 1024;
const RATE_WINDOW_MS = 60 * 1000;
const RATE_MAX = 60;

// Iteration count comes from the client and is only stored; the client does
// the PBKDF2 work. Bound it so a hostile client cannot make viewers burn CPU.
const MIN_ITER = 100000;
const MAX_ITER = 1000000;

const ID_RE = /^[0-9a-f]{16}$/;

const store = new Map(); // id -> {ct, iv, salt, iterations, adata, burn, expires}
const rate = new Map();  // ip -> {n, resetAt}

function send(res, status, obj) {
  const body = JSON.stringify(obj);
  res.writeHead(status, {
    'Content-Type': 'application/json; charset=utf-8',
    'Content-Length': Buffer.byteLength(body),
    'Cache-Control': 'no-store',
  });
  res.end(body);
}

function readBody(req) {
  return new Promise((resolve, reject) => {
    let n = 0;
    const chunks = [];
    req.on('data', (c) => {
      n += c.length;
      if (n > MAX_BODY) { reject(new Error('too large')); req.destroy(); return; }
      chunks.push(c);
    });
    req.on('end', () => resolve(Buffer.concat(chunks).toString('utf8')));
    req.on('error', reject);
  });
}

function rateOk(ip) {
  const now = Date.now();
  const r = rate.get(ip);
  if (!r || r.resetAt < now) {
    rate.set(ip, { n: 1, resetAt: now + RATE_WINDOW_MS });
    return true;
  }
  r.n++;
  return r.n <= RATE_MAX;
}

// split/join, not replace(): the values are not regex-escaped by us.
function serveHtml(res, file, subs) {
  fs.readFile(path.join(__dirname, 'public', file), 'utf8', (err, src) => {
    if (err) { res.writeHead(404); return res.end('not found'); }
    let out = src;
    for (const k of Object.keys(subs)) out = out.split(k).join(subs[k]);
    res.writeHead(200, {
      'Content-Type': 'text/html; charset=utf-8',
      'Cache-Control': 'no-store',
    });
    res.end(out);
  });
}

const server = http.createServer(async (req, res) => {
  const ip = (req.headers['x-forwarded-for'] || req.socket.remoteAddress || '')
    .split(',')[0].trim();
  if (!rateOk(ip)) return send(res, 429, { error: 'rate limited' });

  const url = new URL(req.url, 'http://internal');

  if (req.method === 'POST' && url.pathname === '/api/paste') {
    let p;
    try { p = JSON.parse(await readBody(req)); }
    catch { return send(res, 400, { error: 'bad json' }); }

    const { id, ct, iv, salt, adata, iterations, burn } = p;
    if (!ID_RE.test(id)) return send(res, 400, { error: 'bad id' });
    if (store.has(id)) return send(res, 409, { error: 'id collision' });
    if (!ct || !iv || !salt || !adata) return send(res, 400, { error: 'missing fields' });

    const it = Number(iterations);
    if (!Number.isInteger(it) || it < MIN_ITER || it > MAX_ITER) {
      return send(res, 400, { error: 'iterations out of range' });
    }

    store.set(id, {
      ct, iv, salt, adata, iterations: it, burn: !!burn,
      expires: Date.now() + TTL_MS,
    });
    return send(res, 200, { id });
  }

  if (req.method === 'GET' && url.pathname.startsWith('/api/paste/')) {
    const id = url.pathname.slice('/api/paste/'.length);
    if (!ID_RE.test(id)) return send(res, 400, { error: 'bad id' });
    const e = store.get(id);
    if (!e) return send(res, 404, { error: 'not found' });
    if (e.expires < Date.now()) {
      store.delete(id);
      return send(res, 404, { error: 'expired' });
    }
    if (e.burn) store.delete(id);
    return send(res, 200, {
      ct: e.ct, iv: e.iv, salt: e.salt, iterations: e.iterations, adata: e.adata,
    });
  }

  if (req.method === 'GET' && url.pathname === '/health') {
    return send(res, 200, { ok: true });
  }

  if (req.method === 'GET' && url.pathname === '/') {
    // PrivateBin-style address: /?<pasteId>#<key>
    if (ID_RE.test(url.search.slice(1))) return serveHtml(res, 'view.html', {});
    return serveHtml(res, 'new.html', { '__SHORTENER__': SHORTENER });
  }

  send(res, 404, { error: 'not found' });
});

setInterval(() => {
  const now = Date.now();
  for (const [k, v] of store) if (v.expires < now) store.delete(k);
}, 60 * 1000).unref();

server.listen(PORT, '127.0.0.1', () => {
  console.log(`khepri core listening on 127.0.0.1:${PORT}`);
});
